# 逻辑运算符
#   and or not
#   and：x and y，若x为False时返回x，否者返回y
#   or：x or y，若x为True时返回x，否则返回y
#   当两边是表达式的时候，重点不是算出两边的值再bool值判断，而是先拿到左侧结果判断bool在根据and/or，决定返回哪一侧
