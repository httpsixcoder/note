# 身份运算符(是否用一个对象，即地址)
#   is , not is
num1 = 10
num2 = 10
print(num1 == num2)  # num1等于num2
print(num1 is num2)  # num1等于num2，地址也一样
list1 = [1, 2, 3]
list2 = list1[:]
print(list1 == list2)  # 值一样
print(list1 is list2)  # 地址不一样
