# 位运算 (需要转换成二进制再运算,以补码形式进行计算)
#   &按位或  |按位或  ^按位异或  ~按位取反
#   <<左移[*2]  >>有右移[/2]
#   正数:原码,反码,补码都一样
#   负数:原码(最高位符号位1),反码(除最高位不变其余取反),补码(反码加1)
#   注意运算结束后是"补码",需要求出原码之后显示(负数需要注意,正数三码合一)
#   17>>3 (8,4,2)实际答案是2
#   -12>>3 (-6,-3,-1.5)实际答案是-2 向负无穷取整,向下取整

